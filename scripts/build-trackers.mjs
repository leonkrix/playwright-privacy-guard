// Makes src/trackers-data.ts from the third-party-web dataset (MIT, Patrick Hulce, data from the HTTP
// Archive). Run it with `pnpm trackers` when you update the dependency, and commit the result: the
// package ships the small list, not the dependency.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const { entities } = require('third-party-web');
const version = require('third-party-web/package.json').version;

// The categories of the dataset, in the order they are written to the list
const categories = [...new Set(entities.map((entity) => entity.categories[0] ?? 'other'))].sort();

// One entry per product (the name people know), with its category
const names = [];
const lines = [];
for (const entity of entities) {
  const category = entity.categories[0] ?? 'other';
  const index = names.length;
  names.push(`${entity.name}\t${String(categories.indexOf(category))}`);
  for (const domain of entity.domains) {
    // *.example.com is example.com: subdomains are tried one by one on the way up
    const bare = domain.toLowerCase().replace(/^\*\./, '');
    if (!bare.includes('*')) {
      lines.push(`${bare}\t${String(index)}`);
    }
  }
}
lines.sort();

const text = `// Generated by scripts/build-trackers.mjs from third-party-web ${version} (MIT, Patrick Hulce). Do not edit.
export const TRACKER_DATA_VERSION = ${JSON.stringify(version)};
export const TRACKER_CATEGORIES: readonly string[] = ${JSON.stringify(categories)};
/** One product per line: name, tab, index of its category */
export const TRACKER_PRODUCTS: string = ${JSON.stringify(names.join('\n'))};
/** One domain per line: domain, tab, index of its product */
export const TRACKER_DOMAINS: string = ${JSON.stringify(lines.join('\n'))};
`;
writeFileSync(new URL('../src/trackers-data.ts', import.meta.url), text);
console.log(
  `${String(names.length)} products, ${String(lines.length)} domains, ${String(Math.round(text.length / 1024))} KB`,
);
